#!/usr/bin/env python3
"""Regenerate the conda lockfiles that Dockerfile.pyinstaller installs.

The glibc builder's CPython and its bundled runtime libraries come from
conda-forge. A plain `conda create` re-solves against the newest packages on
every build, so the env is instead installed from an explicit lockfile per
arch (exact URLs and sha256 digests, no solving). Dependabot does not support
conda, so rerun this script to update them:

    python src/inspect_ai/tool/_sandbox_tools_utils/lock_conda_env.py

It solves in the builder's pinned base image for each target subdir (no
emulation needed; packages are downloaded, not run) and writes
conda-{amd64,arm64}.lock next to this script. Conda has no release cooldown,
so packages published in the last 7 days are listed for review.
"""

import json
import re
import subprocess
import time
from pathlib import Path

SPECS = ["python=3.10", "libstdcxx-ng"]
SUBDIRS = {"amd64": "linux-64", "arm64": "linux-aarch64"}
COOLDOWN_SECONDS = 7 * 24 * 60 * 60
SCRIPT_DIR = Path(__file__).parent

# Runs in the base image: solve, download, then print each package's repodata
# record in link (install) order.
SOLVE = """
set -e
conda create -n build --dry-run --json SPECS > /tmp/plan.json
conda create -n build --download-only -y -q SPECS > /dev/null
python - <<'EOF'
import json
plan = json.load(open("/tmp/plan.json"))["actions"]["LINK"]
print(json.dumps([
    json.load(open(f"/opt/conda/pkgs/{p['dist_name']}/info/repodata_record.json"))
    for p in plan
]))
EOF
"""


def base_image() -> str:
    dockerfile = (SCRIPT_DIR / "Dockerfile.pyinstaller").read_text()
    match = re.search(r"^FROM (\S+)", dockerfile, re.MULTILINE)
    assert match, "no FROM line in Dockerfile.pyinstaller"
    return match.group(1)


def lock(arch: str, subdir: str, image: str) -> None:
    result = subprocess.run(
        ["docker", "run", "--rm", "--platform", "linux/amd64"]
        + ["-e", f"CONDA_SUBDIR={subdir}", image]
        + ["sh", "-c", SOLVE.replace("SPECS", " ".join(SPECS))],
        check=True,
        capture_output=True,
        text=True,
    )
    records = json.loads(result.stdout)
    lines = [f"{r['url']}#sha256:{r['sha256']}" for r in records]
    header = [
        f"# Generated by lock_conda_env.py for {subdir}: {' '.join(SPECS)}",
        f"# from {image}",
        "@EXPLICIT",
    ]
    (SCRIPT_DIR / f"conda-{arch}.lock").write_text("\n".join(header + lines) + "\n")
    recent = [
        r["fn"]
        for r in records
        if time.time() - r.get("timestamp", 0) / 1000 < COOLDOWN_SECONDS
    ]
    print(f"conda-{arch}.lock: {len(records)} packages")
    for fn in recent:
        print(f"  published in the last 7 days, review: {fn}")


def main() -> None:
    image = base_image()
    for arch, subdir in SUBDIRS.items():
        lock(arch, subdir, image)


if __name__ == "__main__":
    main()
